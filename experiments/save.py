#!/usr/bin/env python3
"""Save finished JUPITER training runs into experiments/ and rebuild experiments/README.md.

  experiments/save.py                    save every finished run that is not saved yet
  experiments/save.py <run_id> ["note"]  save (or refresh) one run, optionally with a note

Needs an open `ssh jupiter` session.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORK = "/e/scratch/weatherai/shared_work"
HEADER = """# Experiments

Generated by `experiments/save.py` (do not edit by hand): run it after jobs finish to add them,
or `experiments/save.py <run_id> "note"` to add a note. Each folder has the full `config.json`,
the per-step `train_metrics.json` and the `summary.json` shown here.
"""


def remote(cmd: str) -> str:
    """Stdout of cmd on JUPITER ("" if it fails, e.g. a crashed run has no metrics file)."""
    return subprocess.run(["ssh", "jupiter", cmd], capture_output=True, text=True).stdout


def finished_runs() -> dict[str, dict]:
    """Training jobs of the last 90 days that are no longer queued or running, by run id."""
    out = remote("sacct -X -n -P -S now-90days -o JobID,JobName,State,Start,Elapsed")
    runs = {}
    for line in out.splitlines():
        job, name, state, start, elapsed = line.split("|")
        if name.startswith("weathergen_") and name.endswith("_part1_train"):
            if state not in ("PENDING", "RUNNING"):
                runs[name.split("_")[1]] = dict(job=job, state=state.split()[0], start=start, elapsed=elapsed)
    return runs


def setup_of(err_log: str) -> str:
    """Config files of the run, from the srun line in the job's stderr."""
    tokens = remote(f"grep -a -m1 'run_train.py train' {err_log}").split()

    def arg(flag):
        value = tokens[tokens.index(flag) + 1] if flag in tokens[:-1] else ""
        return "" if value.startswith("--") else value

    base = Path(arg("--base-config")).name or "default_config.yml"
    overlays = [Path(p).name for p in arg("--config").split(":") if p and "config_command_line" not in p]
    return " + ".join([base, *overlays])


def save(run: str, job: dict, note: str | None) -> None:
    out = HERE / f"{job['start'][:10]}_{run}"
    out.mkdir(exist_ok=True)
    logs = f"{WORK}/logs/{run}"

    metrics = remote(f"cat {WORK}/results/{run}/{run}_train_metrics.json")
    if metrics:
        (out / "train_metrics.json").write_text(metrics)
    config = remote(f"cat {WORK}/models/{run}/model_{run}.json")
    if config:
        config = json.loads(config)
        config.pop("mlflow", None)  # the team's tracking address from the private repo
        (out / "config.json").write_text(json.dumps(config, indent=1) + "\n")

    rows = [json.loads(line) for line in metrics.splitlines() if line.strip()]
    train = [r for r in rows if r.get("stage") == "train" and "elapsed_training_time_seconds" in r]
    elapsed = [r["elapsed_training_time_seconds"] for r in train]
    gpu = [r["performance.memory.train.max_allocated_gib"] for r in rows if "performance.memory.train.max_allocated_gib" in r]
    # the training step (.0), not the batch script, which "completes" even when training fails
    state, rss = (remote(f"sacct -n -P -j {job['job']}.0 -o State,MaxRSS").strip().split("|") + ["", ""])[:2]
    rss_kib = rss.rstrip("K")
    error = remote(f"grep -a -h -E '^0: [A-Za-z_.]+(Error|Exception): ' {logs}/output.{job['job']}.txt | tail -1")
    error = re.sub(r"/\S+/", "", error.split(": ", 1)[-1]).strip()  # keep file names, drop directories

    old = out / "summary.json"
    summary = dict(
        run=run,
        job=job["job"],
        date=job["start"][:10],
        state=state.split()[0] if state else job["state"],
        elapsed=job["elapsed"],
        setup=setup_of(f"{logs}/weathergen.part1.{job['job']}.err"),
        steps=len(train),
        # skip the first 10 steps (warm-up)
        s_per_step=round((elapsed[-1] - elapsed[9]) / (len(elapsed) - 10), 2) if len(elapsed) > 10 else None,
        gpu_peak_gib=round(max(gpu), 2) if gpu else None,
        host_rss_gib=round(int(rss_kib) / 2**20, 1) if rss_kib.isdigit() else None,
        error=error[:150],
        note=note if note is not None else (json.loads(old.read_text())["note"] if old.exists() else ""),
    )
    old.write_text(json.dumps(summary, indent=1) + "\n")
    print(f"saved {out.name}: {summary['state']}, {summary['steps']} steps")


def write_index() -> None:
    lines = [
        HEADER,
        "| Run | Date | Setup | State | Steps | s/step | Peak GPU GiB | Host RSS GiB | Notes |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    summaries = [(p.parent.name, json.loads(p.read_text())) for p in HERE.glob("*/summary.json")]
    for folder, s in sorted(summaries, key=lambda x: int(x[1]["job"]), reverse=True):  # newest first
        notes = "; ".join(x for x in (s["note"], s["error"]) if x)
        cells = [f"[{s['run']}]({folder}/)", s["date"], s["setup"], s["state"], s["steps"],
                 s["s_per_step"], s["gpu_peak_gib"], s["host_rss_gib"], notes]
        lines.append("| " + " | ".join("" if c is None else str(c) for c in cells) + " |")
    (HERE / "README.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    runs = finished_runs()
    if len(sys.argv) > 1:
        run = sys.argv[1]
        if run not in runs:
            sys.exit(f"{run}: no finished training job in the last 90 days")
        save(run, runs[run], sys.argv[2] if len(sys.argv) > 2 else None)
    else:
        saved = {p.parent.name.split("_")[-1] for p in HERE.glob("*/summary.json")}
        for run, job in runs.items():
            if run not in saved:
                save(run, job, None)
    write_index()
